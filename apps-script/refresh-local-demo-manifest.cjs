/**
 * 掃描專案根目錄 `assets/images/`，產生 `assets/mc-local-demo-manifest.js`
 * 供本機預覽以專內標本圖作為示範圖庫（在 UI 中需於 local-preview 程式之前載入該腳本）。
 * 在新增/刪除圖片後可重新執行本檔。
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const imageDir = path.join(root, 'assets', 'images');
const outFile = path.join(root, 'assets', 'mc-local-demo-manifest.js');

const EXTS = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.JPG', '.JPEG', '.PNG', '.WEBP', '.GIF']);

if (!fs.existsSync(imageDir)) {
  console.warn('[refresh-local-demo-manifest] 找不到目錄，寫出空陣列:', imageDir);
  const empty =
    '/** Auto-generated — no assets/images folder */\n' +
    'window.MC_LOCAL_DEMO_RELPATHS = [];\n';
  fs.writeFileSync(outFile, empty, 'utf8');
  process.exit(0);
}

const rels = fs
  .readdirSync(imageDir, { withFileTypes: true })
  .filter(function (d) {
    if (!d.isFile()) return false;
    if (d.name === '.DS_Store' || d.name === '.gitkeep') return false;
    return EXTS.has(path.extname(d.name));
  })
  .map(function (d) {
    return 'assets/images/' + d.name;
  })
  .sort();

const json = JSON.stringify(rels, null, 0);
const body =
  '/** Auto-generated by apps-script/refresh-local-demo-manifest.cjs — do not hand-edit. */\n' +
  'window.MC_LOCAL_DEMO_RELPATHS = ' +
  json +
  ';\n';

fs.writeFileSync(outFile, body, 'utf8');
console.log('[refresh-local-demo-manifest] wrote', rels.length, 'paths to', path.relative(root, outFile));
