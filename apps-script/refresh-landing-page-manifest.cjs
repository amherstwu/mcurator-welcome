/**
 * 掃描 landing / workflow 圖片目錄，產生 `assets/mc-landing-page-images.js`。
 * 在新增/刪除圖片後可重新執行： node apps-script/refresh-landing-page-manifest.cjs
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const imagesRoot = path.join(root, 'assets', 'images');
const outFile = path.join(root, 'assets', 'mc-landing-page-images.js');

const EXTS = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.JPG', '.JPEG', '.PNG', '.WEBP', '.GIF']);

/** Workflow FP heroes first (preload priority), then landing_page demos. */
const SCAN_DIRS = ['herbarium', 'insect', 'fossil', 'field', 'wildlife', 'bird', 'marine', 'microbe', 'landing_page'];

function listRels(subdir) {
  const dir = path.join(imagesRoot, subdir);
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .filter(function (d) {
      if (!d.isFile()) return false;
      if (d.name === '.DS_Store' || d.name === '.gitkeep') return false;
      return EXTS.has(path.extname(d.name));
    })
    .map(function (d) {
      return 'assets/images/' + subdir + '/' + d.name;
    })
    .sort();
}

const rels = [];
for (var i = 0; i < SCAN_DIRS.length; i++) {
  rels.push.apply(rels, listRels(SCAN_DIRS[i]));
}

const json = JSON.stringify(rels, null, 0);
const body =
  '/** Auto-generated by apps-script/refresh-landing-page-manifest.cjs — do not hand-edit. */\n' +
  'window.MC_LANDING_PAGE_IMAGE_RELS = ' +
  json +
  ';\n';

fs.writeFileSync(outFile, body, 'utf8');
console.log('[refresh-landing-page-manifest] wrote', rels.length, 'paths to', path.relative(root, outFile));
